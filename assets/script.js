const page = window.location.pathname.split("/").pop() || "index.html";
const supportedLanguages = Object.keys(translations);

function getStoredLanguage() {
  try {
    return localStorage.getItem("synergia-lang");
  } catch {
    return null;
  }
}

function storeLanguage(lang) {
  try {
    localStorage.setItem("synergia-lang", lang);
  } catch {
    // Ignore storage failures and keep the current session language only.
  }
}

function detectBrowserLanguage() {
  const browserLanguage = (navigator.language || navigator.userLanguage || "").toLowerCase();
  const primaryLanguage = browserLanguage.split("-")[0];
  return supportedLanguages.includes(primaryLanguage) ? primaryLanguage : "en";
}

function getInitialLanguage() {
  return getStoredLanguage() || detectBrowserLanguage();
}

function formatDate(value, lang) {
  if (/^\d{4}-\d{2}-\d{2}$/.test(value)) {
    const date = new Date(`${value}T00:00:00`);
    return new Intl.DateTimeFormat(lang, { day: "2-digit", month: "long", year: "numeric" }).format(date);
  }

  if (/^\d{4}-\d{2}$/.test(value)) {
    const date = new Date(`${value}-01T00:00:00`);
    return new Intl.DateTimeFormat(lang, { month: "long", year: "numeric" }).format(date);
  }

  return value;
}

function createCard(concert, lang) {
  const labels = translations[lang] || translations.de;
  const card = document.createElement("article");
  card.className = "panel card";

  const title = document.createElement("h3");
  title.textContent = concert.venue;

  const date = document.createElement("p");
  date.textContent = formatDate(concert.date, lang);

  const city = document.createElement("p");
  city.textContent = concert.city;

  const program = document.createElement("p");
  program.textContent = concert.program;

  const ticket = document.createElement("a");
  ticket.className = "btn";
  ticket.href = concert.ticketUrl;
  ticket.target = "_blank";
  ticket.rel = "noreferrer";
  ticket.textContent = labels.ticketLabel;

  card.append(title, date, city, program, ticket);
  return card;
}

function renderConcertsLanding(lang) {
  const upcomingEl = document.getElementById("upcoming-list");
  const noUpEl = document.getElementById("no-upcoming");
  if (!upcomingEl) return;
  upcomingEl.innerHTML = "";
  if (!concerts.upcoming.length) {
    if (noUpEl) noUpEl.textContent = translations[lang].noUpcoming;
  } else {
    concerts.upcoming.slice(0, 2).forEach((event) => upcomingEl.appendChild(createCard(event, lang)));
    if (noUpEl) noUpEl.textContent = "";
  }
}

function renderConcertsFull(lang) {
  const upcomingEl = document.getElementById("upcoming-list");
  const archiveEl = document.getElementById("archive-list");
  if (!upcomingEl || !archiveEl) return;
  upcomingEl.innerHTML = "";
  archiveEl.innerHTML = "";
  if (!concerts.upcoming.length) {
    const empty = document.createElement("article");
    empty.className = "panel";
    empty.textContent = translations[lang].noUpcoming;
    upcomingEl.appendChild(empty);
  } else {
    concerts.upcoming.forEach((event) => upcomingEl.appendChild(createCard(event, lang)));
  }
  concerts.archive
    .slice()
    .sort((a, b) => (a.date > b.date ? -1 : 1))
    .forEach((event) => archiveEl.appendChild(createCard(event, lang)));
}

function setActiveNav() {
  document.querySelectorAll(".main-nav a").forEach((link) => {
    link.classList.toggle("nav-active", link.getAttribute("href") === page);
  });
}

function applyLanguage(lang) {
  const safeLang = supportedLanguages.includes(lang) ? lang : "en";
  const labels = translations[safeLang] || translations.en;
  document.documentElement.lang = safeLang;
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    if (labels[key]) node.textContent = labels[key];
  });
  document.querySelectorAll(".lang-btn").forEach((button) => {
    button.classList.toggle("is-active", button.dataset.lang === safeLang);
  });
  if (page === "index.html" || page === "") {
    renderConcertsLanding(safeLang);
  } else if (page === "termine.html") {
    renderConcertsFull(safeLang);
  }
  storeLanguage(safeLang);
}

document.querySelectorAll(".lang-btn").forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.lang));
});

setActiveNav();
const initialLang = getInitialLanguage();
applyLanguage(initialLang);
