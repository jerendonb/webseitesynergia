applyLanguage(initialLang);

// Dip-to-black transition: homepage ↔ subpage
(function () {
  const veil = document.getElementById("page-veil");
  if (!veil) return;
  const FADE_OUT_MS = 100;
  const FLAG = "synergia-dip";

  // Fade from black when arriving via a dip-to-black transition
  if (sessionStorage.getItem(FLAG)) {
    sessionStorage.removeItem(FLAG);
    veil.classList.add("veil-in");
    requestAnimationFrame(() => {
      requestAnimationFrame(() => {
        veil.classList.remove("veil-in");
      });
    });
  }

  // Fade to black when leaving the home page (any link) or when leaving a
  // subpage toward the home page (only the brand / index.html link).
  const isHome = page === "index.html" || page === "";

  document.addEventListener("click", function (e) {
    const link = e.target.closest("a[href]");
    if (!link) return;
    const href = link.getAttribute("href");
    if (
      !href ||
      href.startsWith("http") ||
      href.startsWith("mailto") ||
      href.startsWith("#") ||
      link.hasAttribute("download") ||
      link.target === "_blank"
    ) return;

    const goingHome = href === "index.html" || href === "./index.html";

    // Trigger only from home (any link) or from subpage to home
    if (!isHome && !goingHome) return;

    e.preventDefault();
    sessionStorage.setItem("synergia-dip", "1");
    veil.classList.add("veil-in");
    setTimeout(function () {
      window.location.href = href;
    }, FADE_OUT_MS);
  });
}());
